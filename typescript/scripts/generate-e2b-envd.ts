import { readFile, writeFile } from "node:fs/promises";
const root = new URL("../../python/src/arker/", import.meta.url);
const script = await readFile(new URL("_guest_e2b_envd.py", root), "utf8");
const manifest = JSON.parse(await readFile(new URL("_guest_e2b_envd_manifest.json", root), "utf8"));
await writeFile(new URL("../src/compat/e2b-envd-guest.generated.ts", import.meta.url),
  `// Generated by scripts/generate-e2b-envd.ts from the canonical Python guest assets.\n` +
  `export const guestScript = ${JSON.stringify(script)};\n` +
  `export const manifest = ${JSON.stringify(manifest)} as const;\n`);
