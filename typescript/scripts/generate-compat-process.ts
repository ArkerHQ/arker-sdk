import { readFile, writeFile } from "node:fs/promises";

const source = await readFile(new URL("../../python/src/arker/_guest_process.py", import.meta.url), "utf8");
await writeFile(new URL("../src/compat/guest-process.generated.ts", import.meta.url),
  `// Generated by scripts/generate-compat-process.ts from the shared guest protocol.\nexport default ${JSON.stringify(source)};\n`);

const signals = JSON.parse(await readFile(new URL("../../python/src/arker/_linux_signals.json", import.meta.url), "utf8"));
await writeFile(new URL("../src/compat/linux-signals.generated.ts", import.meta.url),
  `// Generated by scripts/generate-compat-process.ts from the Linux guest signal contract.\nexport default ${JSON.stringify(signals)} as Record<string, string>;\n`);

const filesystem = await readFile(new URL("../../python/src/arker/_guest_filesystem.py", import.meta.url), "utf8");
await writeFile(new URL("../src/compat/guest-filesystem.generated.ts", import.meta.url),
  `// Generated by scripts/generate-compat-process.ts from the shared guest filesystem protocol.\nexport default ${JSON.stringify(filesystem)};\n`);
