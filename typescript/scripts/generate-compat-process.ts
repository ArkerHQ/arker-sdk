import { readFile, writeFile } from "node:fs/promises";

for (const [source, target] of [
  ["_guest_process.py", "guest-process"],
  ["_guest_modal_defaults.py", "modal-defaults-guest"],
  ["_linux_signals.json", "linux-signals"],
  ["_guest_filesystem.py", "guest-filesystem"],
  ["_guest_e2b_mount_ready.py", "e2b-mount-ready"],
  ["_guest_daytona_filesystem.py", "daytona-filesystem"],
]) {
  const text = await readFile(new URL(`../../python/src/arker/${source}`, import.meta.url), "utf8");
  const isJson = source.endsWith(".json");
  const value = JSON.stringify(isJson ? JSON.parse(text) : text);
  await writeFile(new URL(`../src/compat/${target}.generated.ts`, import.meta.url),
    `// Generated by scripts/generate-compat-process.ts from ${source}.\nexport default ${value}${isJson ? " as Record<string, string>" : ""};\n`);
}
